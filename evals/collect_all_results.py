"""Consolidate every evaluation run into one authoritative results file.

Reads the per-run logs under logs/ plus the externally-supplied VGGT baseline in
results/vggt_baseline.csv, and writes:

    results/all_metrics.csv   one tidy row per (experiment, sequence)
    results/RESULTS.md        formatted tables with protocol and caveats

Numbers are read from the logs, never hardcoded, so re-running after a new
evaluation regenerates the file.

Usage:  python evals/collect_all_results.py
"""

import csv
import math
from pathlib import Path


REPO = Path(__file__).resolve().parent.parent
LOGS = REPO / "logs"
OUT = REPO / "results"

# log directory -> (experiment label, dataset, config description)
EXPERIMENTS = [
    ("dvlt_w16_loops",    "dvlt-fr1-ungated",  "TUM fr1",  "loops on, NOT verified (lc_verify=bypass)"),
    ("dvlt_w16_noloops",  "dvlt-fr1-noloops",  "TUM fr1",  "loop closure disabled (--max_loops 0)"),
    ("dvlt_w16_attn",     "dvlt-fr1-attn",     "TUM fr1",  "loops on, attention-gated at 0.95"),
    ("dvlt_all_w16_attn", "dvlt-tum21-attn",   "TUM fr1+fr2+fr3", "loops on, attention-gated at 0.95"),
    ("dvlt_7scenes_w16",  "dvlt-7scenes-attn", "7-Scenes", "loops on, attention-gated at 0.95"),
]

SHORT = {"rgbd_dataset_": ""}


def short(name: str) -> str:
    for k, v in SHORT.items():
        name = name.replace(k, v)
    return name.replace("freiburg", "fr")


def read_results(path: Path) -> dict[str, float]:
    out: dict[str, float] = {}
    if not path.exists():
        return out
    for row in csv.DictReader(open(path)):
        try:
            out[row["Dataset"]] = float(row["RMSE"])
        except (ValueError, KeyError, TypeError):
            out[row["Dataset"]] = float("nan")
    return out


def stats(values: list[float]) -> tuple[int, int, float, float]:
    ok = [v for v in values if not math.isnan(v)]
    if not ok:
        return len(values), 0, float("nan"), float("nan")
    s = sorted(ok)
    median = s[len(s) // 2] if len(s) % 2 else (s[len(s) // 2 - 1] + s[len(s) // 2]) / 2
    return len(values), len(ok), sum(ok) / len(ok), median


def fmt(v: float) -> str:
    return "FAILED" if math.isnan(v) else f"{v:.4f}"


def main() -> None:
    OUT.mkdir(exist_ok=True)

    # ---- gather -------------------------------------------------------------
    data: dict[str, dict[str, float]] = {}
    meta: dict[str, tuple[str, str]] = {}
    for dirname, label, dataset, config in EXPERIMENTS:
        d = LOGS / dirname
        res = read_results(d / "tum_results.txt") or read_results(d / "7scenes_results.txt")
        if res:
            data[label] = res
            meta[label] = (dataset, config)

    baseline: dict[str, dict[str, float]] = {}
    bpath = OUT / "vggt_baseline.csv"
    if bpath.exists():
        lines = [l for l in open(bpath) if not l.startswith("#")]
        for row in csv.DictReader(lines):
            baseline.setdefault(f"vggt-fr1-{row['config']}", {})[row["sequence"]] = float(row["rmse"])
    for k in baseline:
        meta[k] = ("TUM fr1", "stock VGGT-SLAM 2.0 (external, different hardware)")

    all_runs = {**data, **baseline}

    # ---- tidy csv -----------------------------------------------------------
    with open(OUT / "all_metrics.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["experiment", "dataset", "config", "sequence", "ate_rmse_m"])
        for label, res in all_runs.items():
            ds, cfg = meta[label]
            for seq, v in sorted(res.items()):
                w.writerow([label, ds, cfg, seq, "" if math.isnan(v) else f"{v:.6f}"])

    # ---- markdown -----------------------------------------------------------
    L: list[str] = []
    A = L.append
    A("# DVLT-in-VGGT-SLAM — consolidated ATE results")
    A("")
    A("Metric: ATE RMSE (m), `evo_ape tum ... -as` (Umeyama alignment + scale correction).")
    A("Protocol: `--submap_size 16 --min_disparity 50 --conf_threshold 25 --lc_thres 0.95`,")
    A("SL(4) submap alignment, DVLT `K=12`, bf16, RTX 4050 Laptop 6 GB.")
    A("Generated by `evals/collect_all_results.py` — do not edit by hand.")
    A("")

    # Table 1: fr1 loop-closure ablation + baseline
    A("## 1. TUM fr1 — loop-closure ablation, and the matched VGGT baseline")
    A("")
    cols = ["dvlt-fr1-ungated", "dvlt-fr1-noloops", "dvlt-fr1-attn", "vggt-fr1-w16", "vggt-fr1-w32"]
    cols = [c for c in cols if c in all_runs]
    hdr = ["sequence"] + [c.replace("dvlt-fr1-", "DVLT ").replace("vggt-fr1-", "VGGT ") for c in cols]
    A("| " + " | ".join(hdr) + " |")
    A("|" + "---|" * len(hdr))
    seqs = sorted({s for c in cols for s in all_runs[c]})
    for s in seqs:
        A(f"| {short(s)} | " + " | ".join(fmt(all_runs[c].get(s, float('nan'))) for c in cols) + " |")
    means = [stats(list(all_runs[c].values())) for c in cols]
    A("| **mean** | " + " | ".join(f"**{m[2]:.4f}**" for m in means) + " |")
    A("| *scored* | " + " | ".join(f"*{m[1]}/{m[0]}*" for m in means) + " |")
    A("")
    A("`vggt-fr1-w16` is the **matched** comparison (same protocol, same sequences).")
    A("`vggt-fr1-w32` uses a different submap size and unconfirmed provenance — **not**")
    A("directly comparable to anything else in this table.")
    A("")

    # Remaining tables: one per larger experiment
    for label, title in [("dvlt-tum21-attn", "2. TUM fr1+fr2+fr3 (21 sequences) — attention-gated"),
                         ("dvlt-7scenes-attn", "3. 7-Scenes (seq-01 of each scene) — attention-gated")]:
        if label not in all_runs:
            continue
        A(f"## {title}")
        A("")
        A("| sequence | ATE RMSE (m) |")
        A("|---|---|")
        for s, v in sorted(all_runs[label].items()):
            A(f"| {short(s)} | {fmt(v)} |")
        n, ok, mean, med = stats(list(all_runs[label].values()))
        A(f"| **mean** | **{mean:.4f}** |")
        A(f"| **median** | **{med:.4f}** |")
        A(f"| *scored* | *{ok}/{n}* |")
        A("")

    A("## Caveats")
    A("")
    A("- **Means are only comparable within a dataset.** The 21-sequence and 7-Scenes")
    A("  means cover harder/different data than TUM fr1; comparing them across tables,")
    A("  or against the fr1 VGGT baseline, is meaningless.")
    A("- **Single run per configuration.** The pose fit uses RANSAC and is not")
    A("  deterministic; per-sequence differences below ~10% are not established.")
    A("- **No VGGT baseline exists for tables 2 and 3.** VGGT-1B does not fit in 6 GB,")
    A("  so those rows are DVLT in isolation and say nothing about H1.")
    A("- **`FAILED` means no trajectory was produced**, never a score of 0.0.")
    A("")

    (OUT / "RESULTS.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"wrote {OUT/'all_metrics.csv'}")
    print(f"wrote {OUT/'RESULTS.md'}")


if __name__ == "__main__":
    main()
